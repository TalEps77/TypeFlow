// A built-in Dictionary pack: the English terms Israeli developers say with a
// Hebrew accent inside Hebrew sentences — קומיט, פוש, פול ריקווסט, קלוד אמדי —
// mapped to how they are actually written. Applied by DictionaryService after
// transcription like any user entry, so "אחרי הקומיט תעשה פוש" comes out as
// "אחרי ה־commit תעשה push". Everything here is an ordinary DictionaryEntry
// once added: editable, deletable, exportable.
//
// Curation rule: a trigger must be a transliteration nobody writes as a Hebrew
// word. Loanwords with an accepted Hebrew spelling (אובייקט, פונקציה, מודל,
// אינדקס) and transliterations that collide with real Hebrew words (פול the
// bean, פורק the verb, הלם, של, מיין) are left out on purpose — the Dictionary
// is conservative by design (SM-C2), and a user who wants them adds them once.

