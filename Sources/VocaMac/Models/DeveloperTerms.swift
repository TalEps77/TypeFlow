    /// re-added behind the user's back after they delete entries from it.
    static let seededDefaultsKey = "vocamac.dictionary.developerTermsSeeded"

    /// Adds the pack to an empty Dictionary exactly once per install. A
    /// Dictionary that already has entries belongs to someone who set it up
    /// before this pack existed; they get the button in Settings instead.
    @MainActor
    static func seedIfFresh(into store: DictionaryStore, defaults: UserDefaults = VocaDefaults.store) {
        guard !defaults.bool(forKey: seededDefaultsKey) else { return }
        defaults.set(true, forKey: seededDefaultsKey)
        guard store.entries.isEmpty else { return }
        store.merge(hebrewToEnglish)
    }

